 where not exists (select 1 from categories x where x.name in (c.old_name, c.new_name))
union all
select 'ITEM_NOT_FOUND', m.old_name, m.new_name from m
 where not exists (select 1 from items i where i.name in (m.old_name, m.new_name))
union all
select 'NAME_CONFLICT', m.new_name, i.name from m
 join items i on i.name = m.new_name and m.new_name <> m.old_name
 where exists (select 1 from items j where j.name = m.old_name)
union all
select 'DB_ITEM_NOT_IN_FILE', i.name, cat.name from items i
 join categories cat on cat.id = i.category_id
 where cat.kind = 'asset'
   and i.name not in (select old_name from m) and i.name not in (select new_name from m)
order by 1, 2;
